"""Regenerate static/icons.js from an @mdi/js checkout (Apache-2.0).

Usage: python3 tools/build_icons.py /path/to/@mdi/js/mdi.js
Only the icons named below are copied, so the bundle stays small.
"""
import json
import re
import sys
from pathlib import Path

NAMES = """mdiCloudOutline mdiServer mdiBucketOutline mdiKeyVariant mdiDatabase mdiScaleBalance mdiLan
mdiIpNetworkOutline mdiShieldOutline mdiWall mdiIpOutline mdiAccount mdiAccountGroup
mdiBadgeAccountHorizontalOutline mdiFileDocumentOutline mdiFormatListBulleted mdiKey mdiLambda
mdiCardAccountDetailsOutline mdiTagOutline mdiDomain mdiGithub mdiAccountMultiple mdiSourceRepository
mdiSourceBranch mdiCodeTags mdiOfficeBuilding mdiAccountOutline mdiAccountGroupOutline
mdiApplicationOutline mdiFolderOutline mdiServerNetwork mdiPailOutline mdiAws mdiGoogleCloud
mdiShieldKeyOutline mdiHexagonMultipleOutline mdiEthernet mdiCube mdiLockOutline mdiPin mdiStar
mdiHome mdiRocket mdiDiamondStone mdiBank mdiEarth mdiEmailOutline mdiPhone mdiWeb
mdiCreditCardOutline mdiBriefcaseOutline mdiFlag mdiHeart mdiAlert mdiLink
mdiMenu mdiArrowLeft mdiArrowRight mdiCodeBraces mdiCodeBracesBox mdiDotsHorizontal mdiFilterVariant mdiClockOutline mdiBrush mdiGraphOutline mdiSelectGroup mdiVectorLink mdiMinus mdiPlus mdiCrosshairsGps mdiMagnify mdiClose mdiChevronDoubleLeft mdiChevronDoubleRight mdiArrowExpandAll mdiPlayOutline mdiMinusCircleOutline mdiDownload mdiMapOutline mdiCog mdiHelpCircleOutline mdiPinOutline mdiSelect mdiSwapHorizontal mdiLasso mdiCheckCircle mdiAlertCircleOutline mdiContentSave mdiThemeLightDark mdiTable mdiMenuRight mdiMenuDown mdiChevronRight mdiVectorPolyline mdiFolderOpenOutline mdiFileOutline mdiDatabaseOutline mdiCircleMultipleOutline mdiDockLeft mdiTrashCanOutline mdiPencilOutline mdiImageOutline mdiKeyboardOutline mdiSitemapOutline mdiChartBubble mdiArrowExpand mdiSelectionDrag mdiEye mdiEyeOff mdiCheck mdiContentCopy mdiRefresh mdiSort mdiSortAscending mdiSortDescending mdiFormatText mdiPaletteOutline mdiResize mdiPlusBoxMultipleOutline mdiChartTimelineVariant mdiCircleOutline""".split()


def main(src: str) -> None:
    text = Path(src).read_text()
    out = {}
    for name in NAMES:
        m = re.search(r'export var %s = "([^"]+)"' % name, text)
        if m:
            out[name[3:]] = m.group(1)
    dest = Path(__file__).resolve().parent.parent / "static" / "icons.js"
    dest.write_text("// Generated by tools/build_icons.py from @mdi/js (Apache-2.0).\nwindow.ICONS = "
                    + json.dumps(out, indent=0) + ";\n")
    print(f"wrote {len(out)} icons to {dest}")


if __name__ == "__main__":
    main(sys.argv[1])
